def money_line(d: Deed, text: str, name: str, *, after: str = ""):
    """Exact service sentence, fillable amount, then ₪."""
    d.ensure(20)
    tail = ("₪ " + after).strip() if after else "₪"
    tw_tail = tw(tail, 9.4) + 8
    lab_w = min(tw(text, 9.4) + 8, d.iw - tw_tail - 70)
    d.page.insert_htmlbox(
        pymupdf.Rect(MR - lab_w, d.y, MR, d.y + 14),
        H(text, size=9.4, align="start", lh=1.15),
        css=CSS,
        archive=ARCH,
    )
    d.page.insert_htmlbox(
        pymupdf.Rect(ML, d.y, ML + tw_tail, d.y + 14),
        H(tail, size=9.4, face="M", align="start", lh=1.15),
        css=CSS,
        archive=ARCH,
    )
    yline = d.y + 13.4
    d.page.draw_line(
        pymupdf.Point(ML + tw_tail + 2, yline),
        pymupdf.Point(MR - lab_w - 6, yline),
        color=INK,
        width=0.5,
    )
    d.field(pymupdf.Rect(ML + tw_tail + 2, d.y + 1, MR - lab_w - 6, yline - 0.3), name=name)
    d.y += 20


def client_sig(d: Deed):
    d.ensure(78)
    labels = ["שם הלקוח", "חתימת הלקוח", "תאריך"]
    names = ["sig_client_name", "sig_client", "sig_client_date"]
    gap = 10.0
    w = (d.iw - gap * 2) / 3
    h = 70.0
    x = MR
    for lab, name in zip(labels, names):
        x0 = x - w
        box = pymupdf.Rect(x0, d.y, x, d.y + h)
        d.page.draw_rect(box, color=INK, width=0.45)
        d.page.draw_rect(pymupdf.Rect(x0, d.y, x, d.y + 3.0), color=YELLOW, fill=YELLOW, width=0)
        d.page.draw_rect(pymupdf.Rect(x - 18, d.y, x, d.y + 3.0), color=RED, fill=RED, width=0)
        d.page.insert_htmlbox(
            pymupdf.Rect(x0 + 4, d.y + 8, x - 4, d.y + 22),
            H(lab, size=8.2, face="M", align="center"),
            css=CSS,
            archive=ARCH,
        )
        d.page.draw_line(
            pymupdf.Point(x0 + 10, d.y + 52),
            pymupdf.Point(x - 10, d.y + 52),
            color=INK,
            width=0.5,
        )
        d.field(pymupdf.Rect(x0 + 10, d.y + 28, x - 10, d.y + 50), name=name)
        x = x0 - gap
    d.y += h + 8


